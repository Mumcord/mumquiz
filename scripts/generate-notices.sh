#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from the licences of the dependencies (cargo-about). CI does the
# same on main after dependency changes (.github/workflows/notices.yml), so running it by hand is
# optional. Needs cargo-about at the version in scripts/tools.env.
#
# Licence policy: it fails when a dependency has a licence that is not 'accepted' in about.toml, so an
# incompatible dependency is noticed at once. The list must match the [licenses].allow list of
# deny.toml. The question bank is data, not a dependency: its upstream licence stays in NOTICE.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
# shellcheck source=scripts/tools.env
source scripts/tools.env

command -v cargo-about >/dev/null 2>&1 || PATH="$HOME/.cargo/bin:$PATH"
command -v cargo-about >/dev/null 2>&1 || {
  echo "cargo-about not found. Install: cargo install cargo-about --version $CARGO_ABOUT_VERSION --locked --features cli" >&2
  exit 1
}
installed="$(cargo about --version | awk '{print $2}')"
if [ "$installed" != "$CARGO_ABOUT_VERSION" ]; then
  echo "warning: cargo-about $installed is installed, CI uses $CARGO_ABOUT_VERSION; the output may differ." >&2
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

body="$tmp/notices.md"
cargo about generate --locked scripts/notices/about.hbs > "$body" || {
  echo "error: cargo-about failed. If it reports 'failed to satisfy license requirements', a" >&2
  echo "dependency uses a licence that is not 'accepted' in about.toml. Replace the dependency, or" >&2
  echo "add the licence there only after checking that it is compatible with the AGPL-3.0." >&2
  exit 1
}

{
  cat <<'HEAD'
Mumquiz - third-party notices
===========================

The bot itself is licensed under the GNU AGPL v3 only (see LICENSE and NOTICE). It links the Rust
crates listed below, each with its licence text. This file is generated by
scripts/generate-notices.sh from about.toml and scripts/notices/about.hbs; do not edit it by hand.

HEAD
  cat "$body"
} > THIRD_PARTY_NOTICES.md

crates=$(grep -c '^- ' "$root/THIRD_PARTY_NOTICES.md")
licences=$(grep -c '^## ' "$root/THIRD_PARTY_NOTICES.md")
echo "THIRD_PARTY_NOTICES.md: $crates crates, $licences licence texts"
